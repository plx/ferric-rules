use slotmap::KeyData;
use std::cmp::Ordering;

/// Maximum recency length generated by these harnesses (the inline capacity).
const MAX_RECENCY: usize = 4;

/// A concrete, valid (odd-version) token key distinct for each `i`.
fn token(i: u32) -> TokenId {
    TokenId::from(KeyData::from_ffi((1u64 << 32) | u64::from(i)))
}

/// Independent three-way comparison.
fn spec_cmp<T: PartialOrd>(a: T, b: T) -> Ordering {
    if a < b {
        Ordering::Less
    } else if a > b {
        Ordering::Greater
    } else {
        Ordering::Equal
    }
}

// ---------------------------------------------------------------------------
// Specification of conflict resolution ("`Less`" means "fires first")
// ---------------------------------------------------------------------------

/// Independent descending insertion sort.
fn spec_sorted_desc(values: &[u64]) -> ([u64; MAX_RECENCY], usize) {
    let mut out = [0u64; MAX_RECENCY];
    let mut n = 0;
    for &v in values {
        let mut pos = n;
        while pos > 0 && out[pos - 1] < v {
            out[pos] = out[pos - 1];
            pos -= 1;
        }
        out[pos] = v;
        n += 1;
    }
    (out, n)
}

/// CLIPS LEX recency comparison: the tags of each activation are compared
/// pairwise from the most recent downward; the first more recent tag fires
/// first; if every compared tag is equal, the activation with more tags fires
/// first.
fn spec_lex_recency(a: &[u64], b: &[u64]) -> Ordering {
    let (sa, na) = spec_sorted_desc(a);
    let (sb, nb) = spec_sorted_desc(b);
    let mut i = 0;
    loop {
        if i == na && i == nb {
            return Ordering::Equal;
        }
        if i == na {
            return Ordering::Greater;
        }
        if i == nb {
            return Ordering::Less;
        }
        if sa[i] != sb[i] {
            return spec_cmp(sb[i], sa[i]);
        }
        i += 1;
    }
}

/// Activation data from which both the production `Activation` and the
/// specification are built. `seq` is the activation's chronology.
#[derive(Clone, Copy)]
struct RawActivation {
    rule: u32,
    token: u32,
    salience: i32,
    complexity: u16,
    seq: u64,
    recency: [u64; MAX_RECENCY],
    len: usize,
}

impl RawActivation {
    /// Symbolic data with exactly `len` recency tags.
    fn with_len(len: usize) -> Self {
        assert!(len <= MAX_RECENCY);
        Self {
            rule: 0,
            token: 0,
            salience: kani::any(),
            complexity: kani::any(),
            seq: kani::any(),
            recency: kani::any(),
            len,
        }
    }

    fn recency(&self) -> &[u64] {
        &self.recency[..self.len]
    }

    fn first_recency(&self) -> u64 {
        if self.len == 0 {
            0
        } else {
            self.recency[0]
        }
    }

    fn to_activation(self) -> Activation {
        Activation {
            id: ActivationId::default(),
            rule: RuleId(self.rule),
            token: token(self.token),
            salience: Salience::new(self.salience),
            complexity: self.complexity,
            timestamp: Timestamp::ZERO,
            activation_seq: ActivationSeq::new(self.seq),
            recency: SmallVec::from_buf_and_len(self.recency.map(RecencyTag), self.len),
        }
    }
}

/// Conflict resolution as documented in `strategy.rs` and on `AgendaKey`:
/// higher salience fires first under every strategy; then depth fires newer
/// activations first, breadth older ones, LEX compares recencies (above), MEA
/// compares the first pattern's recency and then falls back to LEX; then
/// higher specificity (complexity); then older activations.
fn spec_fires_first(
    strategy: ConflictResolutionStrategy,
    a: &RawActivation,
    b: &RawActivation,
) -> Ordering {
    let by_salience = spec_cmp(b.salience, a.salience);
    if by_salience != Ordering::Equal {
        return by_salience;
    }
    let by_strategy = match strategy {
        ConflictResolutionStrategy::Depth => spec_cmp(b.seq, a.seq),
        ConflictResolutionStrategy::Breadth => spec_cmp(a.seq, b.seq),
        ConflictResolutionStrategy::Lex => spec_lex_recency(a.recency(), b.recency()),
        ConflictResolutionStrategy::Mea => match spec_cmp(b.first_recency(), a.first_recency()) {
            Ordering::Equal => spec_lex_recency(a.recency(), b.recency()),
            decided => decided,
        },
    };
    if by_strategy != Ordering::Equal {
        return by_strategy;
    }
    let by_complexity = spec_cmp(b.complexity, a.complexity);
    if by_complexity != Ordering::Equal {
        return by_complexity;
    }
    spec_cmp(a.seq, b.seq)
}

