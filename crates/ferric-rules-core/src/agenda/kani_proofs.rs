/// `add` never overflows the sequence counter: on an empty agenda with any
/// `next_seq` (the agenda invariant holds for every value), the activation
/// receives the current sequence, or zero after the exhaustion rebase, and
/// `next_seq` becomes its successor. Bounds: one add of a concrete activation
/// (depth); `next_seq` is the only symbolic input.
#[kani::proof]
#[kani::unwind(6)]
fn add_never_overflows_sequence_counter() {
    let mut agenda = Agenda::new();
    let start: u64 = kani::any();
    agenda.next_seq = ActivationSeq::new(start);
    let id = agenda.add(concrete_activation());
    let expected = if start == u64::MAX { 0 } else { start };
    assert_eq!(
        agenda.get(id).unwrap().activation_seq,
        ActivationSeq::new(expected)
    );
    assert_eq!(agenda.next_seq, ActivationSeq::new(expected + 1));
    kani::cover!(start == u64::MAX);
    kani::cover!(start == u64::MAX - 1);
}

fn concrete_activation() -> Activation {
    Activation {
        id: ActivationId::default(),
        rule: RuleId(0),
        token: token(0),
        salience: Salience::DEFAULT,
        complexity: 0,
        timestamp: Timestamp::ZERO,
        activation_seq: ActivationSeq::ZERO,
        recency: SmallVec::new(),
    }
}

/// `clear` from a non-empty agenda empties every index, drops the derived rule
/// index and resets the sequence counter. (`validate_consistency` on the
/// cleared agenda runs out of memory; see the module documentation.) Bounds:
/// one concrete activation added from a symbolic starting `next_seq` (depth).
#[kani::proof]
#[kani::unwind(6)]
fn clear_resets_sequence_and_indexes() {
    let mut agenda = Agenda::new();
    let start: u64 = kani::any();
    agenda.next_seq = ActivationSeq::new(start);
    agenda.add(concrete_activation());
    agenda.clear();
    assert!(agenda.is_empty());
    assert!(agenda.ordering.is_empty());
    assert!(agenda.id_to_key.is_empty());
    assert!(agenda.token_to_activations.is_empty());
    assert!(agenda.rule_ordering.is_none());
    assert_eq!(agenda.next_seq, ActivationSeq::ZERO);
    assert_eq!(agenda.strategy(), ConflictResolutionStrategy::Depth);
    kani::cover!(start == u64::MAX);
}

/// A new agenda passes the production `validate_consistency` under every
/// strategy and starts at sequence zero.
#[kani::proof]
#[kani::unwind(6)]
fn new_agenda_is_consistent() {
    for strategy in [
        ConflictResolutionStrategy::Depth,
        ConflictResolutionStrategy::Breadth,
        ConflictResolutionStrategy::Lex,
        ConflictResolutionStrategy::Mea,
    ] {
        let agenda = Agenda::with_strategy(strategy);
        assert!(agenda.validate_consistency().is_ok());
        assert!(agenda.is_empty());
        assert_eq!(agenda.strategy(), strategy);
        assert_eq!(agenda.next_seq, ActivationSeq::ZERO);
    }
}
