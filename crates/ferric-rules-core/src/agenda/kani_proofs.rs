#[kani::proof]
fn recency_tag_encoding_round_trips() {
    let t: u64 = kani::any();
    match RecencyTag::from_timestamp(Timestamp::new(t)) {
        None => assert_eq!(t, u64::MAX),
        Some(tag) => {
            assert!(t < u64::MAX);
            assert_eq!(tag.timestamp(), Some(Timestamp::new(t)));
            assert!(tag > RecencyTag::ABSENT);
        }
    }
    assert_eq!(RecencyTag::ABSENT.timestamp(), None);

    // Every tag is either absent or the encoding of exactly one timestamp.
    let tag = RecencyTag(kani::any());
    match tag.timestamp() {
        None => assert_eq!(tag, RecencyTag::ABSENT),
        Some(ts) => assert_eq!(RecencyTag::from_timestamp(ts), Some(tag)),
    }

    // Encoding is strictly monotone: fact recency order is timestamp order.
    let u: u64 = kani::any();
    if let (Some(a), Some(b)) = (
        RecencyTag::from_timestamp(Timestamp::new(t)),
        RecencyTag::from_timestamp(Timestamp::new(u)),
    ) {
        assert_eq!(a.cmp(&b), spec_cmp(t, u));
    }
    kani::cover!(t == u64::MAX);
    kani::cover!(t == 0);
    kani::cover!(t < u && u < u64::MAX);
}

#[kani::proof]
fn activation_seq_next_is_successor_below_max() {
    let x: u64 = kani::any_where(|x: &u64| *x < u64::MAX);
    let seq = ActivationSeq::new(x);
    assert_eq!(seq.get(), x);
    assert_eq!(seq.next().get(), x + 1);
    assert!(seq.next() > seq);
    assert_eq!(ActivationSeq::ZERO.get(), 0);
    kani::cover!(x == u64::MAX - 1);
}

/// `ActivationSeq::next` is unguarded at `u64::MAX` (overflow panic with
/// overflow checks, wrap to zero without them). `Agenda::add` never reaches it:
/// see `add_never_overflows_sequence_counter`.
#[kani::proof]
#[kani::should_panic]
fn activation_seq_next_overflows_at_max() {
    let _ = ActivationSeq::new(u64::MAX).next();
}

// ---------------------------------------------------------------------------
// build_key: exact characterization against the specification
// ---------------------------------------------------------------------------

fn check_build_key(
    strategy: ConflictResolutionStrategy,
    len_a: usize,
    len_b: usize,
) -> (Ordering, RawActivation, RawActivation) {
    let agenda = Agenda::with_strategy(strategy);
    let a = RawActivation::with_len(len_a);
    let b = RawActivation::with_len(len_b);
    let ka = agenda.build_key(&a.to_activation());
    let kb = agenda.build_key(&b.to_activation());
    let ord = ka.cmp(&kb);
    assert_eq!(ord, spec_fires_first(strategy, &a, &b));
    // Salience dominates every strategy.
    if a.salience > b.salience {
        assert_eq!(ord, Ordering::Less);
    }
    // Distinct activation sequences give distinct keys, so `add` never
    // overwrites an `ordering` entry.
    if a.seq != b.seq {
        assert_ne!(ord, Ordering::Equal);
    }
    assert_eq!(ka.salience, std::cmp::Reverse(Salience::new(a.salience)));
    assert_eq!(ka.seq, ActivationSeq::new(a.seq));
    kani::cover!(a.salience > b.salience);
    kani::cover!(a.salience == b.salience && ord == Ordering::Less);
    kani::cover!(a.salience == b.salience && ord == Ordering::Greater);
    (ord, a, b)
}

#[kani::proof]
fn build_key_depth_matches_spec() {
    let (ord, a, b) = check_build_key(ConflictResolutionStrategy::Depth, 1, 0);
    // Depth: at equal salience the newer activation fires first.
    if a.salience == b.salience && a.seq > b.seq {
        assert_eq!(ord, Ordering::Less);
    }
}

#[kani::proof]
fn build_key_breadth_matches_spec() {
    let (ord, a, b) = check_build_key(ConflictResolutionStrategy::Breadth, 1, 0);
    // Breadth: at equal salience the older activation fires first.
    if a.salience == b.salience && a.seq < b.seq {
        assert_eq!(ord, Ordering::Less);
    }
}

fn check_build_key_lex(len_a: usize, len_b: usize) {
    let (ord, a, b) = check_build_key(ConflictResolutionStrategy::Lex, len_a, len_b);
    let same_recency = spec_lex_recency(a.recency(), b.recency()) == Ordering::Equal;
    // LEX: equal recency falls back to higher specificity, then older.
    if a.salience == b.salience && same_recency && a.complexity > b.complexity {
        assert_eq!(ord, Ordering::Less);
    }
    if a.salience == b.salience && same_recency && a.complexity == b.complexity && a.seq < b.seq {
        assert_eq!(ord, Ordering::Less);
    }
}

fn check_build_key_mea(len_a: usize, len_b: usize) {
    let (ord, a, b) = check_build_key(ConflictResolutionStrategy::Mea, len_a, len_b);
    // MEA: the first pattern's recency decides first.
    if a.salience == b.salience && a.first_recency() > b.first_recency() {
        assert_eq!(ord, Ordering::Less);
    }
    kani::cover!(
        a.salience == b.salience && a.first_recency() == b.first_recency() && ord == Ordering::Less
    );
}

/// LEX and MEA `build_key` harnesses, one per length of the first
/// activation's recency (concrete), each covering every length in `0..=4` for
/// the second; tags, salience, complexity and sequences are full-width
/// symbolic. (All 25 length pairs in one harness exhaust memory.)
macro_rules! lex_mea_build_key_harnesses {
    ($($len_a:literal => $lex:ident, $mea:ident;)*) => {$(
        #[kani::proof]
        #[kani::unwind(6)]
        fn $lex() {
            for len_b in 0..=MAX_RECENCY {
                check_build_key_lex($len_a, len_b);
            }
        }

        #[kani::proof]
        #[kani::unwind(6)]
        fn $mea() {
            for len_b in 0..=MAX_RECENCY {
                check_build_key_mea($len_a, len_b);
            }
        }
    )*};
}

lex_mea_build_key_harnesses! {
    0 => build_key_lex_matches_spec_len_0, build_key_mea_matches_spec_len_0;
    1 => build_key_lex_matches_spec_len_1, build_key_mea_matches_spec_len_1;
    2 => build_key_lex_matches_spec_len_2, build_key_mea_matches_spec_len_2;
    3 => build_key_lex_matches_spec_len_3, build_key_mea_matches_spec_len_3;
    4 => build_key_lex_matches_spec_len_4, build_key_mea_matches_spec_len_4;
}

/// Swapping recency positions `k` and `k + 1` for every `k >= lowest` leaves
/// the key unchanged, for every length in `2..=4`.
fn check_adjacent_swaps_keep_key(strategy: ConflictResolutionStrategy, lowest: usize) {
    let agenda = Agenda::with_strategy(strategy);
    for len in 2..=MAX_RECENCY {
        for k in lowest..len - 1 {
            let a = RawActivation::with_len(len);
            let mut b = a;
            b.recency.swap(k, k + 1);
            assert!(agenda.build_key(&a.to_activation()) == agenda.build_key(&b.to_activation()));
            kani::cover!(len == MAX_RECENCY && a.recency[k] != a.recency[k + 1]);
        }
    }
}

/// LEX keys depend only on the multiset of recency tags: every adjacent
/// transposition leaves the key unchanged, and adjacent transpositions
/// generate all permutations, so (by transitivity of `==`) the key is
/// invariant under every permutation. Bounds: recency lengths 2..=4,
/// full-width tags.
#[kani::proof]
#[kani::unwind(6)]
fn lex_key_ignores_recency_order() {
    check_adjacent_swaps_keep_key(ConflictResolutionStrategy::Lex, 0);
}

/// MEA keys depend only on the first recency tag and the multiset: adjacent
/// transpositions after the first position (which generate all permutations
/// fixing it) leave the key unchanged. Bounds: as for LEX.
#[kani::proof]
#[kani::unwind(6)]
fn mea_key_ignores_order_after_first_recency() {
    check_adjacent_swaps_keep_key(ConflictResolutionStrategy::Mea, 1);
}

