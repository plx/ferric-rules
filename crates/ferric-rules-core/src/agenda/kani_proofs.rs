//! Kani proof harnesses for `agenda` (see docs/verification.md).
//!
//! Proved, for every input within the bounds stated on each harness:
//!
//! - `recency_tag_encoding_round_trips`: `RecencyTag::from_timestamp` is
//!   defined exactly below `u64::MAX`, `timestamp` inverts it, every tag is
//!   `ABSENT` or the encoding of exactly one timestamp, and the encoding is
//!   strictly monotone and above `ABSENT`.
//! - `activation_seq_next_is_successor_below_max`; and
//!   `activation_seq_next_overflows_at_max` (`should_panic`), which records
//!   that `ActivationSeq::next` itself is unguarded at `u64::MAX`.
//! - `build_key_{depth,breadth}_matches_spec` and
//!   `build_key_{lex,mea}_matches_spec_len_{0..4}`: for two arbitrary
//!   activations, `build_key(a).cmp(&build_key(b))` equals `spec_fires_first`,
//!   an independent specification written from `strategy.rs` and the
//!   `AgendaKey` documentation (`Less` fires first): higher salience; then
//!   depth = newer sequence, breadth = older sequence, LEX = the CLIPS recency
//!   comparison (tags sorted most recent first by the specification's own
//!   insertion sort, compared pairwise, more tags wins on an equal prefix), MEA
//!   = larger first-pattern recency (`ABSENT` without patterns) and then LEX;
//!   then higher complexity; then older sequence. Also asserted directly:
//!   salience dominates every strategy; depth prefers the newer and breadth
//!   the older activation at equal salience; LEX falls back to specificity and
//!   then age; MEA's first pattern decides first; activations with distinct
//!   sequences have distinct keys, so `add` never overwrites an `ordering`
//!   entry. Salience, complexity, sequences and recency tags are full-width
//!   symbolic; depth/breadth use recency lengths 1 and 0, LEX/MEA every pair
//!   of lengths in `0..=4` (one harness per first length).
//! - `lex_key_ignores_recency_order`, `mea_key_ignores_order_after_first_recency`:
//!   the LEX key depends only on the multiset of recency tags and the MEA key
//!   only on the first tag and the multiset (every adjacent transposition,
//!   which together generate all permutations; lengths 2..=4).
//! - `add_never_overflows_sequence_counter`: from any `next_seq`, `add` assigns
//!   the current sequence (zero after the exhaustion rebase) and advances the
//!   counter without overflow.
//! - `clear_resets_sequence_and_indexes`: `clear` empties every index, drops
//!   the per-rule index and resets the sequence counter.
//! - `new_agenda_is_consistent`: a new agenda passes `validate_consistency`
//!   under every strategy.
//!
//! The order laws of the key types are proved in `strategy/kani_proofs.rs`.
//!
//! Not covered, because it is intractable for Kani on this code (measured with
//! Kani 0.68 / CBMC 6.11 under a 7 GB address-space limit; "out of memory" is
//! CBMC exit status 6, "timed out" is the 20-minute limit):
//!
//! - Every operation that removes from the `ordering` `BTreeMap` (`pop`,
//!   `pop_matching`, `pop_matching_rule`, `remove_activations_for_token`,
//!   `remove_activations_for_rule`). `BTreeMap::pop_first` on a one-entry
//!   `BTreeMap<AgendaKey, u32>` with concrete keys runs out of memory in
//!   propositional reduction (84 s); one concrete `add` followed by `pop` runs
//!   out of memory (615 s). That `pop` returns the highest-priority activation
//!   therefore rests on the `build_key` characterization above, on
//!   `BTreeMap::pop_first` removing the least key (standard library contract),
//!   and on the agenda invariant; it is not checked end to end.
//! - `validate_consistency` on any agenda that has held an activation: one
//!   concrete `add` followed by `validate_consistency` runs out of memory
//!   (584 s), as does `clear` followed by `validate_consistency`. Invariant
//!   preservation across operations is therefore not checked by Kani.
//! - Operations on agendas with two or more activations: two concrete `add`s
//!   followed by `set_strategy` (symbolic target) or crossing sequence
//!   exhaustion time out, as does inspecting `iter_ordered` on an agenda
//!   seeded with two symbolic activations. `set_strategy`,
//!   `rebase_sequences` with live activations and the derived per-rule index
//!   (`pop_matching_rule`) are not covered.
//! - Operation sequences. The sequence bookkeeping of `add` /
//!   `rebase_sequences` / removals / `clear` is proved for unbounded operation
//!   sequences in the Verus model verification/verus/agenda_sequence_rebase.rs.

use super::*;
